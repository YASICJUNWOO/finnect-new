#: 마디 안의 구멍. `{업체명}` · `{상태}-{번호}`
_HOLE = re.compile(r"\{[^}]+\}")


@dataclass(frozen=True, slots=True)
class Spot:
    """자리 하나. `.md` 한 장이고 그래프의 점 하나다."""

    #: `Company/회사소개` · `Competitor/{업체명}`
    path: str
    #: 기획 §3 의 「담는 것」. **프롬프트가 이걸 그대로 싣는다** — 자리를 고르는 근거다
    holds: str

    @property
    def folder(self) -> str:
        return self.path.split("/", 1)[0]

    @property
    def parts(self) -> tuple[str, ...]:
        return tuple(self.path.split("/"))

    @property
    def holes(self) -> tuple[int, ...]:
        """구멍이 있는 마디의 번호. 없으면 빈 튜플이라 `fixed` 와 짝이다."""
        return tuple(i for i, p in enumerate(self.parts) if _HOLE.search(p))

    @property
    def fixed(self) -> bool:
        return not self.holes

    def fill(self, instance: str | None = None) -> str:
        """인스턴스 이름을 끼운 경로.

        구멍이 없으면 인스턴스를 **무시한다** — LLM 이 딸려 보내도 고정 자리가
        흔들리면 안 된다. 구멍이 둘인 자리에서만 `/` 로 나눠 받는다.

        **이름을 못 받으면 자리 자체를 못 쓴다.** `Competitor/{업체명}` 에 이름 없이
        오면 `Competitor/` 밑에 `{업체명}` 이라는 리터럴 폴더가 생기고, 그건 사용자가
        보는 자리 이름이 된다. 그래서 빈 문자열을 돌려주고 부르는 쪽이 검토 대기로
        떨어뜨린다.
        """
        holes = self.holes
        if not holes:
            return self.path
        names = [p.strip() for p in (instance or "").split("/") if p.strip()]
        if len(names) < len(holes):
            return ""
        parts = list(self.parts)
        for i, name in zip(holes, names, strict=False):
            parts[i] = name
        return "/".join(parts)

    def instance(self, path: str) -> str:
        """채워진 경로에서 인스턴스 이름만 도로 뽑는다. `fill` 의 역이다.

        **프롬프트가 「이 자리에 이미 있는 이름」을 보일 때 쓴다.** 경로를 통째로
        보이면 모델이 `Custom/특허/출원-10-…` 을 통째로 베껴 **다른 자리에 그 이름을
        붙인다** — 실측에서 `Customer/페르소나/출원-10-2025-0114882` 가 나왔다.
        """
        parts = path.split("/")
        if len(parts) != len(self.parts):
            return ""
        return "/".join(parts[i] for i in self.holes)


