def label(bucket: str) -> str:
    """버킷의 화면 이름. 모르는 버킷이면 빈 문자열."""
    return LABELS.get(bucket, "")

_WS = re.compile(r"\s+")


def normalize(value: str | None) -> str:
    """저장값을 표의 키 모양으로 만든다.

    **HTML 엔티티를 여기서 푼다.** DB 에 `기술개발(R&amp;D)` 로 앉아 있는데, 저장할
    때 고치면 "API 가 준 것을 그대로 담는다" 를 어긴다. 읽는 쪽에서 한 번 푼다.
    """
    return _WS.sub("", html.unescape(value or ""))


@dataclass(frozen=True, slots=True)
class Match:
    #: 그 분야가 이 회사 계획에 있나
    hit: bool
    #: 어느 버킷으로 읽었나. 표에 없는 값이면 빈 문자열
    bucket: str
    #: 어떤 낱말이 걸렸나. **왜 그 순서인지 되짚을 때 읽는다**
    cues: tuple[str, ...] = ()


def match(source: str, category: str | None, need_text: str) -> Match:
    """공고의 지원분야가 이 회사가 지금 필요한 것인가.

    `need_text` 는 `CompanyProfile.need_text()` — 로드맵·자금·기술 노드를 이어 붙인
    글이다. **사업 내용 전부를 넣지 않는다** — 그러면 무슨 분야든 걸린다.
    """
    table = TABLES.get(source) or {}
    bucket = table.get(normalize(category), "")
    if not bucket:
        # 표에 없는 분류다. **조용히 통과시키지 않는다** — 새 값이 생기면 밀리고,
        # `--report` 가 세서 표를 고칠 신호를 준다
        return Match(hit=False, bucket="")
    # **공백을 지우지 않는다.** 지우면 낱말 경계를 넘어 걸린다 — 실측으로 잡았다:
    #   "결손금이 자본금을 초과하며"  →  공백을 지우면 `이자` 가 걸려 `융자` 가 맞는다
    # 앵커 대조(`normalize.py`)는 지워야 하고 이쪽은 지우면 안 된다. 저쪽은 LLM 이
    # 공백을 바꿔 쓰는 것을 견뎌야 하고, 이쪽은 **양쪽을 우리가 들고 있다.**
    #
    # 대가 — 위키가 `기술 개발` 처럼 띄어 쓰면 `기술개발` 이 안 걸린다. 오탐보다
    # 낫다: 오탐은 순서를 조용히 망치고 미탐은 밀리기만 한다
    body = need_text or ""
    cues = tuple(c for c in BUCKETS[bucket] if c in body)
    return Match(hit=bool(cues), bucket=bucket, cues=cues)


def unknown_categories(source: str, values: list[str | None]) -> list[str]:
    """표에 없는 분류값. **`--report` 가 찍는다.**"""
    table = TABLES.get(source) or {}
    seen: list[str] = []
    for v in values:
        k = normalize(v)
        if k and k not in table and k not in seen:
            seen.append(k)
    return seen
