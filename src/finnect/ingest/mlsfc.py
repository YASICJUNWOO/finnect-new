"""기업마당 중분류 솎기 표 — **`notice-filter/filter.py` 의 사본이다.**

`src/finnect/` 는 `notice-filter/` 를 임포트하지 않는다(층0 경계 · CLAUDE.md).
그 대가로 이 표가 두 곳에 산다. `match/bodies.py` 가 절 나누기 정규식을 한 벌 더
들고 있는 것과 같은 자리다.

**두 표가 갈리면 조용히 어긋난다** — 여기만 고치면 `notice-filter` 의 퍼널과 우리
코퍼스가 다른 모집단이 되고, 어느 쪽이 맞는지 나중에 못 가린다. `tests/test_ingest_mlsfc.py`
가 원본을 **AST 로 읽어**(임포트하지 않는다) 같음을 막아 둔다.

**값만으로 빼는 축만 여기 온다.** `notice-filter` 의 축 열셋 중 본문을 봐야 하는 것
(축1 · 축2b · 축2c · 축2e · 축2f · 축2g · 축2h · 축2i)은 목록 API 응답에 재료가 없어
옮길 수 없다. 그래서 **이 솎기는 `notice-filter` 판정의 부분집합이다** — 여기를 통과한
것이 곧 타겟 공고라는 뜻이 아니다. 좁히는 것은 코퍼스이지 판정이 아니다.
"""

from __future__ import annotations

#: 축2 — 첨부를 열어 '행정 신청서' 임을 확인한 중분류.
SKIP_MLSFC = frozenset(
    {
        "융자",
        "시험/인증",
        "국내일반인력",
        # 국가 R&D 과제의 수행형태 분류. 순수 연구개발 과제라 제외한다.
        "단독기술개발",
        "공동기술개발",
        "혼합(단독+공동)",
    }
)

#: 축2d — 계획서로 심사하지 않는 세부분야. 표본 20건의 첨부를 전부 열어 확인했다.
SKIP_MLSFC_NOPLAN = frozenset(
    {
        # 인력 — 근로자 채용·유지 요건을 증빙하면 나오는 보조금
        "고용유지",
        "고용환경개선",
        "작업환경개선",
        "교육/훈련/연수",
        "국내전문인력",
        "인력정보제공",
        "해외인력",
        # 금융 — 신용평가·보험 가입으로 심사한다. `융자` 와 같은 계열
        "보증",
        "보험(수출+무역)",
        # 내수 — 정부가 주는 것이 부스 자리·입점 자리다
        "오프라인",
        "온라인",
        "홍보지원",
        "공공구매",
        # 제도 — 인증·지정. 요건 충족 확인이다
        "제도",
    }
)

#: 적재에서 빼는 중분류 스무 개.
SKIPPED = SKIP_MLSFC | SKIP_MLSFC_NOPLAN


def keeps(mlsfc: str | None) -> bool:
    """이 중분류를 적재하나.

    **모르는 값은 남긴다.** 표에 없는 중분류가 새로 생겼을 때 조용히 버리면 코퍼스가
    이유 없이 줄고, 늘어난 쪽은 화면에서 티가 나지만 줄어든 쪽은 안 난다.
    """
    return (mlsfc or "").strip() not in SKIPPED
