def by_number(n: int | None) -> Spot | None:
    """번호로 자리를 꺼낸다. **번호는 1부터이고 범위 밖이면 `None`.**

    0 을 안 쓰는 이유는 JSON 에서 「없음」과 「첫째」가 구분이 안 되어서다.
    **없는 번호에 자리를 지어 주지 않는다** — 지어 주면 그 사실이 엉뚱한 데 앉고,
    앉은 뒤에는 왜 거기 있는지 아무도 못 찾는다.
    """
    if n is None:
        return None
    i = int(n) - 1
    return SPOTS[i] if 0 <= i < len(SPOTS) else None


def render() -> str:
    """프롬프트에 싣는 자리표. `[7] Product/{서비스명}/기능 — 기능 목록, …` 꼴이다.

    **「담는 것」을 같이 싣는다.** 경로만 주면 `Financial/매출` 과 `Plan/KPI` 중
    어디에 「2027년 목표 매출 3억」이 가는지 고를 근거가 없다.
    """
    return "\n".join(f"[{i}] {s.path} — {s.holds}" for i, s in enumerate(SPOTS, 1))


def spot_of(path: str) -> Spot | None:
    """경로가 어느 자리인가. 인스턴스가 채워진 경로도 제 템플릿으로 되돌린다.

    **고정 자리를 먼저 본다.** `Competitor/비교축` 과 `Competitor/{업체명}` 은 마디
    수가 같아서, 템플릿을 먼저 맞추면 비교축이 업체 이름으로 읽힌다.
    """
    parts = tuple(path.split("/"))
    for spot in SPOTS:
        if spot.fixed and spot.parts == parts:
            return spot
    for spot in SPOTS:
        if spot.fixed or len(spot.parts) != len(parts):
            continue
        holes = set(spot.holes)
        pairs = enumerate(zip(spot.parts, parts, strict=True))
        if all(a == b for i, (a, b) in pairs if i not in holes):
            return spot
    return REVIEW if path == REVIEW.path else None
