def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    font_path = docgen.find_font()

    made = [hwpx(), docx(), xlsx(), pptx()]
    if font_path:
        made.append(profile_pdf(docgen.TrueType(font_path)))
        made += scans(font_path)
    else:
        print("한글 폰트를 못 찾았다. PDF 둘과 JPG 를 건너뛴다.", file=sys.stderr)
        print(f"  찾아 본 곳: {[str(c) for c in docgen.FONT_CANDIDATES]}", file=sys.stderr)

    for f in sorted(made):
        print(f"{f.stat().st_size:>9,}  {f.name}")
    return 0


