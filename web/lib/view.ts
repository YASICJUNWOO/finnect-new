/** 목록을 리스트로 볼지 격자로 볼지([ADR-0046](../../docs/adr/0046-격자를-사용자가-고르게-하고-칸에-테두리를-준다.md)).
 *
 * **상태가 주소에 있다.** 클라이언트 상태도 `localStorage` 도 안 쓴다 — `Filters` 가
 * 이미 자바스크립트 없는 GET 폼이고, 주소에 있으면 뒤로 가기·새로 고침·링크 공유가
 * 저절로 된다. **토글 하나 때문에 이 화면에 자바스크립트를 들이지 않는다.** */
export type View = "list" | "grid";

/** 기본값은 리스트다. 격자의 세로 이득이 13px 인데 §4 «목록» 을 어기는 쪽이 격자다 —
 * **어기는 쪽을 기본값으로 두지 않는다.**
 *
 * 주소창은 사용자가 손으로 고칠 수 있는 자리라 아는 값이 아니면 전부 리스트로 돌려세운다.
 * `?view=GRID` 도 `?view=` 도 `?view=드롭테이블` 도 리스트다. */
export function viewOf(raw: string | undefined): View {
  return raw === "grid" ? "grid" : "list";
}
