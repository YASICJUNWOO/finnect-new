/* 시안이 공통으로 쓰는 아주 얇은 헬퍼. 프레임워크가 아니다. */
COPY.esc = function (s) {
  return String(s).replace(/[&<>"]/g, function (c) {
    return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
  });
};

/* why.lead 한 줄을 HTML 로. `strong` 태그 이름은 시안이 정한다 —
 * 굵기로 강조하는 시안도 있고 밑줄·색으로 하는 시안도 있어서다. */
COPY.leadHtml = function (parts, tag) {
  tag = tag || "b";
  return (
    COPY.esc(parts[0]) +
    "<" + tag + ">" + COPY.esc(parts[1]) + "</" + tag + ">" +
    COPY.esc(parts[2])
  );
};
