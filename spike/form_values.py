# 라벨 옆이 비어 있어야 채운다. 이런 것만 들어 있으면 빈 칸으로 본다.
# 관공서 양식이 `000-0000-0000`·`OOOO`·`0000년 00월 00일` 로 형식을 알려 준다.
빈칸표시 = re.compile(r"^[\s0O·.\-()/년월일도시　]*$")


def norm(s: str) -> str:
    """라벨을 대조용으로 정규화한다.

    관공서 양식은 `기   업   명` 처럼 글자 사이를 벌려 칸을 맞춘다. 공백을 지워야
    표에서 라벨 하나를 꺼낼 수 있다. 본문에서 어휘를 *찾는* 경우와는 반대 규칙이다.
    """
    return re.sub(r"[\s　:：]", "", s or "").lower()


def 채울값(라벨_텍스트: str) -> str | None:
    return 값.get(norm(라벨_텍스트))
